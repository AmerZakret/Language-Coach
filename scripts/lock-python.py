"""Refresh wheel hashes for reviewed exact pins; never resolve newer versions.

Run with Python 3.12: python -B scripts/lock-python.py
PyPI JSON supplies hashes for every platform wheel, not only the host wheel.
Review requirements.in first; validate the result in clean Windows/Linux venvs.
"""
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
SERVICE = ROOT / 'lingua_ai_pronunciation_service'
INSTALLER = 'pip==26.2.2'
PIN = re.compile(r'([A-Za-z0-9_.-]+)==([A-Za-z0-9.+-]+)(?:; (.+))?')


def locked(requirement):
    match = PIN.fullmatch(requirement)
    if not match:
        raise ValueError('Only exact reviewed package pins are supported')
    name, version, _ = match.groups()
    with urllib.request.urlopen(f'https://pypi.org/pypi/{name}/{version}/json', timeout=30) as response:
        release = json.load(response)
    wheels = [entry for entry in release['urls']
              if entry['packagetype'] == 'bdist_wheel' and not entry['yanked']]
    hashes = sorted({entry['digests']['sha256'] for entry in wheels})
    if not hashes or any(not re.fullmatch(r'[a-f0-9]{64}', value) for value in hashes):
        raise ValueError(f'No valid published wheel hashes for {name}')
    return requirement + ' \\\n' + ' \\\n'.join('    --hash=sha256:' + value for value in hashes) + '\n'


def main():
    source = SERVICE / 'requirements.in'
    pins = [line.strip() for line in source.read_text(encoding='utf-8').splitlines()
            if line.strip() and not line.startswith('#')]
    names = [PIN.fullmatch(pin).group(1).lower().replace('_', '-') for pin in pins]
    if len(set(names)) != len(names):
        raise ValueError('Duplicate requirement pin')
    digest = hashlib.sha256(source.read_text(encoding='utf-8').encode('utf-8')).hexdigest()
    header = ('# Generated by python -B scripts/lock-python.py; do not edit hashes.\n'
              '# CPython 3.12, Windows/Linux x86_64. Wheels only; no source builds.\n')
    with ThreadPoolExecutor(max_workers=6) as pool:
        entries = list(pool.map(locked, pins))
    installer = locked(INSTALLER)
    (SERVICE / 'requirements.txt').write_text(
        header + f'# requirements.in sha256: {digest}\n--require-hashes\n--only-binary=:all:\n\n'
        + '\n'.join(entries), encoding='utf-8', newline='\n')
    (SERVICE / 'requirements-installer.txt').write_text(
        header + '--require-hashes\n--only-binary=:all:\n\n' + installer,
        encoding='utf-8', newline='\n')
    print(f'Locked {len(entries)} runtime packages and {INSTALLER}; review and clean-install before use.')


if __name__ == '__main__':
    main()
